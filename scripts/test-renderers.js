/* ============================================================================
 * CROSS-RENDERER CONSISTENCY TESTS — run with:  node scripts/test-renderers.js
 *
 * Four renderers (results panel via app.js, client PDF, slideshow, pitch deck)
 * each independently derive the headline savings figures from the same run
 * object. Nothing forced them to agree, and they have disagreed: the pitch deck
 * and slideshow once computed per-strategy incremental savings against the
 * un-overridden base profile, so their per-strategy figures contradicted the
 * scenario totals whenever a fact override was active.
 *
 * Two different numbers for the same thing in front of a client is a
 * credibility failure, and neither test-engine.js (never opens a renderer) nor
 * ui-smoke.js (checks each popup in isolation) can catch it.
 *
 * The renderers are pure HTML-string builders that call TSIQ.render.openWindow
 * / openDeck only at the very end, so this suite stubs those two to capture the
 * HTML instead of opening a browser window. No DOM, no Playwright.
 *
 * On the ET7 rounding: client-facing HEADLINE figures deliberately print via
 * TSIQ.fmt.usdApprox (nearest $100, "≈" prefix) because a projected multi-year
 * number is not a filed-return figure. So agreement is asserted at $100
 * granularity for those, and exactly for the figures printed with fmt.usd.
 * ==========================================================================*/
